// Provenance tags: never let a simulated or estimated number look like a live, settled one.
const TAGS = {
  SIMULATOR: ["SIMULATED", "tag-sim", "Confirmed by the local simulated provider, not a real payment network."],
  TEST_MODE: ["TEST MODE", "tag-test", "Confirmed by a provider in test mode; no real money moved."],
  LIVE: ["LIVE PROVIDER", "tag-live", "Confirmed by a live provider."],
  RECONCILED: ["RECONCILED", "tag-rec", "Matched to a signature-verified provider event with validated amount and currency."],
  ESTIMATE: ["MODEL ESTIMATE", "tag-est", "Model expectation, not an observed outcome."],
  SYNTHETIC: ["SYNTHETIC", "tag-syn", "Generated by the offline simulator; not merchant revenue."],
};
export function Tag({ kind }) {
  const [label, cls, title] = TAGS[kind] || [kind, "tag-neutral", kind];
  return <span className={"tag " + cls} title={title}>{label}</span>;
}

const STATUS_TONE = {
  RECOVERED: "ok", PROVIDER_PENDING: "info", ACTION_QUEUED: "info", OPEN: "info", PENDING_APPROVAL: "warn",
  OUTCOME_UNKNOWN: "warn", NEEDS_REVIEW: "bad", ACTION_FAILED: "bad", EXPIRED: "muted", STILL_FAILED: "muted",
  ACTION_REJECTED: "muted", NO_ACTION: "muted", APPROVED: "ok", REJECTED: "muted", PENDING: "warn",
  PROVIDER_ACCEPTED: "info", UNKNOWN: "warn", FAILED: "bad", QUEUED: "info", DISPATCHING: "info", EXPIRED_APPROVAL: "muted",
  OPTIMAL: "ok", HEURISTIC: "muted", FEASIBLE_TIME_LIMIT: "warn", SUCCEEDED: "ok", RUNNING: "info",
};
export function Status({ value }) {
  if (!value) return <span className="muted">—</span>;
  return <span className={"status status-" + (STATUS_TONE[value] || "muted")}>{human(value)}</span>;
}

export function Loading({ label = "Loading" }) {
  return <div className="state" role="status" aria-live="polite"><span className="spinner" aria-hidden="true" />{label}…</div>;
}
export function Empty({ title = "Nothing here yet", children }) {
  return <div className="state empty"><strong>{title}</strong>{children && <div className="muted">{children}</div>}</div>;
}
export function ErrorBox({ error, onRetry }) {
  const status = error?.status;
  return (
    <div className="state error" role="alert">
      <strong>{status === 0 ? "Can't reach the API" : status === 404 ? "Not found" : "Request failed"}</strong>
      <div>{error?.message || String(error)}{error?.requestId && <span className="mono muted"> · request {error.requestId}</span>}</div>
      {onRetry && <button className="btn" onClick={onRetry}>Retry</button>}
    </div>
  );
}

// Wraps a resource: loading / error / empty / stale handling in one place.
export function Resource({ res, empty, children, label }) {
  if (res.loading && !res.data) return <Loading label={label} />;
  if (res.error && !res.data) return <ErrorBox error={res.error} onRetry={res.reload} />;
  if (!res.data) return null;
  if (empty && empty(res.data)) return typeof children === "function" && children.length > 1 ? children(res.data, true) : <Empty />;
  return (
    <>
      {res.stale && <div className="stale" role="status">Showing data from {when(res.loadedAt?.toISOString())} — refresh failed: {res.error.message}
        <button className="btn btn-sm" onClick={res.reload}>Retry</button></div>}
      {typeof children === "function" ? children(res.data, false) : children}
    </>
  );
}

export function Button({ busy, children, variant = "", ...props }) {
  return (
    <button className={"btn " + variant} disabled={busy || props.disabled} aria-busy={busy ? "true" : "false"} {...props}>
      {busy && <span className="spinner" aria-hidden="true" />}{children}
    </button>
  );
}

// Modal confirmation for financial decisions. Requires explicit click; Esc cancels.
export function ConfirmDialog({ open, title, children, confirmLabel, tone = "primary", requireNote, onConfirm, onCancel }) {
  const [note, setNote] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);
  const ref = useRef(null);
  useEffect(() => {
    if (!open) return undefined;
    setNote(""); setError(null); setBusy(false);
    const prev = document.activeElement;
    setTimeout(() => ref.current?.querySelector("textarea, button")?.focus(), 0);
    const onKey = (e) => { if (e.key === "Escape") onCancel(); };
    window.addEventListener("keydown", onKey);
    return () => { window.removeEventListener("keydown", onKey); prev?.focus?.(); };
  }, [open]); // eslint-disable-line react-hooks/exhaustive-deps
  if (!open) return null;
  const submit = async () => {
    if (requireNote && !note.trim()) { setError("A reason is required."); return; }
    setBusy(true); setError(null);
    try { await onConfirm(note.trim()); } catch (e) { setError(e.message); setBusy(false); }
  };
  return (
    <div className="overlay" onMouseDown={(e) => e.target === e.currentTarget && !busy && onCancel()}>
      <div className="dialog" role="dialog" aria-modal="true" aria-labelledby="dlg-title" ref={ref}>
        <h2 id="dlg-title">{title}</h2>
        <div className="dialog-body">{children}</div>
        <label className="field">
          <span>{requireNote ? "Reason (required, recorded in the audit log)" : "Note (optional, recorded in the audit log)"}</span>
          <textarea value={note} maxLength={500} rows={3} onChange={(e) => setNote(e.target.value)} />
        </label>
        {error && <div className="inline-error" role="alert">{error}</div>}
        <div className="dialog-actions">
          <button className="btn" onClick={onCancel} disabled={busy}>Cancel</button>
          <Button busy={busy} variant={tone === "danger" ? "btn-danger" : "btn-primary"} onClick={submit}>{confirmLabel}</Button>
        </div>
      </div>
    </div>
  );
}

export function KV({ items }) {
  return (
    <dl className="kv">{items.filter(Boolean).map(([k, v]) => (
      <div key={k}><dt>{k}</dt><dd>{v ?? "—"}</dd></div>))}
    </dl>
  );
}

export function Table({ caption, columns, rows, rowKey, onRowClick, empty = "No rows" }) {
  if (!rows?.length) return <Empty title={empty} />;
  return (
    <div className="table-wrap" tabIndex={0} role="region" aria-label={caption}>
      <table>
        <caption className="sr-only">{caption}</caption>
        <thead><tr>{columns.map((c) => <th key={c.key} scope="col" className={c.num ? "num" : ""}>{c.label}</th>)}</tr></thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={rowKey ? rowKey(r) : i} className={onRowClick ? "clickable" : ""}
                onClick={onRowClick ? () => onRowClick(r) : undefined}
                onKeyDown={onRowClick ? (e) => e.key === "Enter" && onRowClick(r) : undefined}
                tabIndex={onRowClick ? 0 : undefined}>
              {columns.map((c) => <td key={c.key} className={c.num ? "num" : ""}>{c.render ? c.render(r) : r[c.key]}</td>)}
            </tr>))}
        </tbody>
      </table>
    </div>
  );
}
